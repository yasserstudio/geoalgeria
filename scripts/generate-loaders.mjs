#!/usr/bin/env node
/**
 * Generate each scoped package's `loaders.cjs`: one loader per data file, each
 * with a literal path a bundler can follow.
 *
 * Why this file exists at all: a scoped package is ESM and used to reach its
 * JSON through a path joined at runtime off `import.meta.url`
 * (`JSON.parse(readFileSync(join(DATA, p)))`). Node follows that, and so does
 * Turbopack, which traces and relocates the read. esbuild and Vite do not, so
 * a bundled app built fine and then threw ENOENT on the first call. That is
 * issue #290; `scripts/check-bundlers.mjs` is its proof, and #282 fixed the
 * same class of fault in the `geoalgeria` umbrella by the same means, a static
 * `require` of a literal path inside a function that stays lazy.
 *
 * The umbrella is CommonJS and could hold its requires inline. A scoped package
 * is ESM, where there is no lazy synchronous JSON import: a static `import` is
 * eager and `import()` is async, and both would change the public API. So the
 * requires live in this generated CommonJS file, which the ESM `index.js`
 * imports as its `load` helper, leaving every call site (`load("atms.json")`)
 * exactly as it was.
 *
 * Generated, not hand-written, so the pattern cannot drift between 26 packages
 * and a regenerated dataset that gains or loses a data file is one command away
 * from a correct loader.
 *
 * Usage:
 *   node scripts/generate-loaders.mjs            write every loaders.cjs
 *   node scripts/generate-loaders.mjs --check    fail if any is out of date
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PACKAGES = join(ROOT, "packages");

/**
 * Packages that build a data file name at run time, so the `load("...")` scan
 * below cannot see their files. Each declares a pattern over its own `data/`
 * instead; the loader map still holds one literal path per matched file.
 *
 * `@geoalgeria/telecom` names its coverage files `<tech>-<operator>.json` on
 * purpose, so a future technology is additive and needs no API change. The
 * pattern keeps that true: drop `4g-djezzy.json` in and the loader follows.
 */
const COMPUTED = {
  telecom: /^[0-9]+g-[a-z]+\.json$/,
};

/** The packages this generator owns: a sector dataset with an ESM index. */
export function loaderPackages() {
  return readdirSync(PACKAGES)
    .filter((dir) => existsSync(join(PACKAGES, dir, "data", "metadata.json")))
    .filter((dir) => existsSync(join(PACKAGES, dir, "index.js")))
    .sort();
}

/**
 * The data files one package's loader must carry: every `load("<file>")` the
 * index asks for by name, plus whatever its computed pattern matches. Each one
 * must exist, so a typo is a build error and never a runtime ENOENT.
 */
export function dataFilesFor(dir) {
  const index = readFileSync(join(PACKAGES, dir, "index.js"), "utf-8");
  const files = new Set([...index.matchAll(/\bload\(\s*"([^"]+\.json)"\s*\)/g)].map((m) => m[1]));
  const pattern = COMPUTED[dir];
  if (pattern) {
    for (const file of readdirSync(join(PACKAGES, dir, "data"))) {
      if (pattern.test(file)) files.add(file);
    }
  }
  const missing = [...files].filter((file) => !existsSync(join(PACKAGES, dir, "data", file)));
  if (missing.length) {
    throw new Error(`${dir}: index.js loads ${missing.join(", ")}, not in data/`);
  }
  return [...files].sort();
}

/** The generated module for one package. */
export function render(name, dir, files) {
  const entries = files.map((file) => `  "${file}": () => require("./data/${file}"),`).join("\n");
  return `// GENERATED by scripts/generate-loaders.mjs. Do not edit by hand.
//
// One loader per data file, each with a literal path a bundler can follow. The
// package is ESM, where there is no lazy synchronous JSON import, so the
// requires live here in CommonJS: \`index.js\` imports this as its \`load\`
// helper and its call sites are unchanged. A \`require\` inside a function stays
// lazy, so importing ${name} still parses nothing.
//
// Why, and what each bundler does with it: scripts/check-bundlers.mjs
// (issues #276 and #290).

const LOADERS = {
${entries}
};

/**
 * Read one of this package's data files.
 *
 * The answer is the module cache's copy, shared by every caller and inlined by
 * a bundler, so treat it as read-only: sort or splice a copy, not this.
 *
 * @param {string} file  file name under \`data/\`, e.g. ${JSON.stringify(files[0])}
 * @returns {any} the parsed JSON
 */
module.exports = function load(file) {
  const loader = LOADERS[file];
  if (!loader) throw new Error(\`${name}: no data file "\${file}" in this package\`);
  return loader();
};
`;
}

/** Every generated artifact has to be in the npm tarball, or it ships broken. */
function withLoaderInFiles(manifest) {
  if (manifest.files?.includes("loaders.cjs")) return null;
  const files = [...manifest.files];
  const at = files.indexOf("index.js");
  files.splice(at < 0 ? files.length : at, 0, "loaders.cjs");
  return { ...manifest, files };
}

function main(check) {
  const stale = [];
  let written = 0;

  for (const dir of loaderPackages()) {
    const manifestPath = join(PACKAGES, dir, "package.json");
    const manifest = JSON.parse(readFileSync(manifestPath, "utf-8"));
    const files = dataFilesFor(dir);
    const wanted = render(manifest.name, dir, files);
    const target = join(PACKAGES, dir, "loaders.cjs");
    const current = existsSync(target) ? readFileSync(target, "utf-8") : null;

    if (current !== wanted) {
      if (check) stale.push(`${dir}/loaders.cjs is ${current === null ? "missing" : "out of date"}`);
      else {
        writeFileSync(target, wanted);
        written += 1;
        console.log(`  wrote ${dir}/loaders.cjs (${files.length} data files)`);
      }
    }

    const patched = withLoaderInFiles(manifest);
    if (patched) {
      if (check) stale.push(`${dir}/package.json files[] does not ship loaders.cjs`);
      else {
        writeFileSync(manifestPath, JSON.stringify(patched, null, 2) + "\n");
        console.log(`  wrote ${dir}/package.json (files[] + loaders.cjs)`);
      }
    }
  }

  if (stale.length) {
    console.error(`generate-loaders --check: ${stale.length} problem(s)`);
    for (const line of stale) console.error(`  ${line}`);
    console.error("  run: node scripts/generate-loaders.mjs");
    process.exit(1);
  }
  console.log(
    check
      ? `  OK: every loaders.cjs is in sync (${loaderPackages().length} packages)`
      : `generate-loaders: ${written} file(s) written`,
  );
}

// Run only as a CLI. The helpers above are exported so
// test/scoped-bundler-safe.test.mjs can re-render each loader and compare;
// importing the module must not write a file.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.includes("--check"));
}
