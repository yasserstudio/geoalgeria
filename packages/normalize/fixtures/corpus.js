// The Golden corpus for the Conservative key and the Loose key.
//
// Every case is one input, the exact keys it must produce, the tokens the key is
// joined from, the Rule ids it proves, and a note saying what it is about. The
// corpus is the contract: the package's own tests, and later every consumer that
// builds an index, assert against this array rather than against hand-written
// cases of their own.
//
// Inputs are real Algerian place names, or synthetic strings built from them.
// Codepoints that are invisible on screen, or that a text editor would happily
// rewrite (combining marks, presentation forms, separator variants), are written
// as escapes so a reader can see what a case is actually about.
//
// `proves` names the Rules in `src/rules.js` a case exercises. An empty list is a
// case that proves a name no Rule touches, or that a declined Rule stayed declined.

