#!/usr/bin/env node
// Runs the bus QA checks (ADR 0003) on a local OSM pull and writes
// research/buses/qa/report.json + REPORT.md. No network.
//
//   node research/buses/qa/run-qa.mjs [--osm-dir research/buses/osm/raw]
//
// The OSM pull is gitignored (collect-osm.mjs writes it); point --osm-dir at
// any checkout that has one.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { buildReport } from "./build-report.mjs";
import { DEFAULTS } from "./check-direction.mjs";
import { geometryGaps } from "./line-identity.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

const flag = process.argv.indexOf("--osm-dir");
if (flag > -1 && !process.argv[flag + 1]) throw new Error("--osm-dir needs a directory");
const osmDir = resolve(flag > -1 ? process.argv[flag + 1] : join(root, "research/buses/osm/raw"));

const elements = readdirSync(osmDir)
  .filter((f) => f === "relations.json" || /^members-\d+\.json$/.test(f))
  .flatMap((f) => readJson(join(osmDir, f)).elements);
const manifest = readJson(join(osmDir, "manifest.json"));
const osmTimestamps = Object.values(manifest.responses).map((r) => r.osm_timestamp).sort();

const data = (name) => readJson(join(root, "packages/buses/data", `${name}.json`));
const lines = data("lines");

// ETUSA's own stop counts (Wikipedia infobox nb_arrets, parsed by parse-etusa.mjs).
const etusaStops = new Map(
  readJson(join(root, "research/buses/etusa-lines-clean.json")).lines.map((l) => [String(l.line), l.stops]),
);
const stopCounts = Object.fromEntries(
  lines
    .filter((l) => l.operator_id === "etusa" && etusaStops.get(String(l.line)) != null)
    .map((l) => [l.id, etusaStops.get(String(l.line))]),
);

const report = buildReport({
  osm: { elements },
  directions: data("directions"),
  memberships: data("station-memberships"),
  stations: data("stations"),
  stopCounts,
});

const tally = (rows, key) => rows.reduce((t, r) => ({ ...t, [r[key]]: (t[r[key]] ?? 0) + 1 }), {});
const failures = {};
for (const d of report.directions) {
  for (const c of d.checks ?? []) if (!c.pass) failures[c.rule] = (failures[c.rule] ?? 0) + 1;
}
const stopRows = report.directions.filter((d) => d.stop_count);
const summary = {
  directions: report.directions.length,
  by_status: tally(report.directions, "status"),
  unvalidated_reasons: tally(report.directions.filter((d) => d.reason), "reason"),
  rule_failures: failures,
  stop_count: { checked: stopRows.length, within_10pct: stopRows.filter((d) => d.stop_count.pass).length },
};

// Every Line accounted for (Owner 2026-11-19): a Line with no Direction has no
// geometry yet, and its reason is derived from the OSM candidates, the refresh
// diff and the Operator stop lists P4 parked.
const listedStops = readJson(join(root, "research/buses/listed-stops/matches.json"));
const gaps = geometryGaps({
  lines,
  directions: data("directions"),
  candidates: readJson(join(root, "research/buses/osm/candidate-lines.json")),
  added: readJson(join(here, "osm-diff.json")).added,
  listedStopLineIds: new Set(listedStops.networks.flatMap((n) => n.lines.map((l) => l.line_id))),
});

const out = {
  generated_by: "research/buses/qa/run-qa.mjs",
  osm_snapshot: { from: osmTimestamps[0], to: osmTimestamps.at(-1) },
  thresholds_m: {
    near_path: DEFAULTS.nearPathM,
    backtrack: DEFAULTS.backtrackM,
    terminus: DEFAULTS.terminusM,
    gap: DEFAULTS.gapM,
  },
  summary,
  directions: report.directions,
  lines_without_geometry: {
    lines: gaps.lines.length,
    by_reason: tally(gaps.lines, "reason"),
    detail: gaps.lines,
    unmatched_relations: gaps.unmatched_relations,
  },
};
writeFileSync(join(here, "report.json"), `${JSON.stringify(out, null, 2)}\n`);

const lineName = new Map(lines.map((l) => [l.id, `${l.operator} ${l.line}`]));
const why = (d) =>
  d.reason ??
  (d.checks.filter((c) => !c.pass).map((c) => (c.failing ? `${c.rule} (${c.failing.length})` : `${c.rule} (${c.gaps} gaps)`)).join(", ") ||
  "all rules pass");
const md = [
  "# Bus QA report",
  "",
  `Generated by \`run-qa.mjs\` from the OSM pull of ${out.osm_snapshot.from.slice(0, 10)}. Rules and statuses: ADR 0003.`,
  "Detail per Direction is in `report.json`.",
  "",
  "| Status | Directions |",
  "| --- | --- |",
  ...Object.entries(summary.by_status).map(([k, v]) => `| \`${k}\` | ${v} |`),
  "",
  `Stop count vs ETUSA figure (advisory): ${summary.stop_count.within_10pct} of ${summary.stop_count.checked} within 10 %.`,
  "",
  "| Line | Direction | Status | Why | Stops (OSM / Operator) |",
  "| --- | --- | --- | --- | --- |",
  ...report.directions.map(
    (d) =>
      `| ${lineName.get(d.line_id) ?? d.line_id} | ${d.direction_id} | ${d.status.replace("osm_member_order_", "")} | ${why(d)} | ${
        d.stop_count ? `${d.stop_count.osm} / ${d.stop_count.operator}${d.stop_count.pass ? "" : " ⚠"}` : ""
      } |`,
  ),
  "",
  "## Lines without geometry",
  "",
  `${gaps.lines.length} Lines have no Direction, so no geometry yet. Reasons come from the OSM candidates, \`osm-diff.json\` and the Operator stop lists in \`listed-stops/matches.json\`.`,
  "",
  "| Reason | Lines |",
  "| --- | --- |",
  ...Object.entries(out.lines_without_geometry.by_reason).map(([k, v]) => `| \`${k}\` | ${v} |`),
  "",
  "| Line | Reason | OSM relations |",
  "| --- | --- | --- |",
  ...gaps.lines.map((g) => `| ${lineName.get(g.line_id)} | ${g.reason} | ${g.osm_relation_ids.join(", ")} |`),
  "",
  `OSM relations of a known Operator that match no Line: ${
    gaps.unmatched_relations.map((r) => `${r.osm_relation_id} (${r.operator_id})`).join(", ") || "none"
  }.`,
  "",
].join("\n");
writeFileSync(join(here, "REPORT.md"), md);

console.log(JSON.stringify(summary, null, 2));
